  static int get stationsWithCoordinates =>
      all.where((station) => station.hasCoordinates).length;

  static List<Station> search(String query) {
    final q = query.trim().toLowerCase();

    if (q.isEmpty) return all;

    return all
        .where(
          (station) =>
      station.nameAr.contains(q) ||
          station.nameEn.toLowerCase().contains(q) ||
          station.lines.any(
                (line) => 'line $line'.contains(q) || 'خط $line'.contains(q),
          ),
    )
        .toList();
  }

  static List<Station> nearestFromLocation(
      double userLat,
      double userLng, {
        int limit = 4,
      }) {
    final withDistance = all
        .where((station) => station.hasCoordinates)
        .map((station) {
      final meters = Geolocator.distanceBetween(
        userLat,
        userLng,
        station.lat!,
        station.lng!,
      );

      return station.copyWith(distanceKm: meters / 1000);
    })
        .toList();

    withDistance.sort(
          (a, b) => (a.distanceKm ?? double.infinity).compareTo(
        b.distanceKm ?? double.infinity,
      ),
    );

    return withDistance.take(limit).toList();
  }
